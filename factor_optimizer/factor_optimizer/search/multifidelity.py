"""Multi-fidelity evaluation: Stage0-5 profile-bound tiers (R61-FI-036).

The pre-existing module already modelled an L0-L4 ``MultiFidelityScheduler``
and ``PromotionCriteria`` funnel.  R61-FI-036 (plan §31) keeps that machinery
and adds the *canonical Stage 0-5* model over it:

- ``EvaluationStage`` — the 6 canonical stages (Stage0 static → Stage5 sealed
  test);
- ``StageEvaluationProfile`` — a Stage bound to a named QE EvidenceProfile
  *id string* (e.g. ``CHEAP_SCREEN_CN_1D``); FO never imports QE, so the
  binding is a validated string reference that resolves only inside QE's
  ``QE_EVIDENCE_PROFILE`` policy;
- ``StageProfileRegistry`` — versioned Stage0-5 bindings;
- ``StageCostTelemetry`` — the plan §31 per-stage cost record (wall/CPU/GPU/
  bytes/candidate count/metric count) with a mutable accumulator so the
  scheduler can later calibrate budgets empirically;
- ``Stage2DiagnosisBudget`` — the diagnosis-directed candidate budget the
  Stage 2 profile carries (generated by FI-034's
  :func:`~factor_optimizer.policy.repair_registry.diagnosis_search_budget`).

The fidelity integer the runner passes to an ``EvaluationProtocol`` maps onto
``FidelityTier`` values 0..4 (pre-existing contract); the Stage names/order
below document which QE EvidenceProfile runs at each point of the funnel.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

from factor_optimizer.policy.repair_registry import (
    DiagnosisSearchBudget,
    RepairBudgetConfig,
    diagnosis_search_budget,
)
from factor_optimizer.policy.repair import DiagnosisKind


class FidelityTier(Enum):
    """
    Evaluation fidelity tiers from cheapest to most expensive.

    L0: Ultra-fast screening (small sample, single metric)
    L1: Fast screening (moderate sample, basic metrics)
    L2: Standard evaluation (full sample, core metrics)
    L3: High-fidelity (full sample, extended metrics, robustness)
    L4: Production-grade (full sample, all metrics, cross-validation)
    """
    L0 = 0
    L1 = 1
    L2 = 2
    L3 = 3
    L4 = 4


