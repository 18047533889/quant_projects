class EvaluationStage(Enum):
    """Canonical multi-fidelity stages (plan §31, R61-FI-036).

    Stage0 static (near-zero factor-value cost; DSL/FE checks only — never a
    QE profile) → Stage5 sealed test (one-shot, single winner).  The plan's
    Stage1-5 each run a named QE EvidenceProfile id (string reference).
    """

    STAGE0 = 0
    STAGE1 = 1
    STAGE2 = 2
    STAGE3 = 3
    STAGE4 = 4
    STAGE5 = 5

    @property
    def fidelity_tier(self) -> FidelityTier:
        """Map a stage onto the legacy L0-L4 fidelity integer contract.

        Stage0 (static) needs no factor-value evaluation; it is represented
        by L0 in the runner contract but never runs a QE profile.  Stage1-4
        map onto L0-L3 (progressive full-evaluation tiers); Stage5 (sealed
        one-shot) maps onto L4.
        """
        mapping = {
            EvaluationStage.STAGE0: FidelityTier.L0,
            EvaluationStage.STAGE1: FidelityTier.L0,
            EvaluationStage.STAGE2: FidelityTier.L1,
            EvaluationStage.STAGE3: FidelityTier.L2,
            EvaluationStage.STAGE4: FidelityTier.L3,
            EvaluationStage.STAGE5: FidelityTier.L4,
        }
        return mapping[self]


def _validate_profile_id(profile_id: str) -> str:
    if not isinstance(profile_id, str) or not profile_id.strip():
        raise ValueError(
            "evidence_profile must be a non-empty QE EvidenceProfile id string"
        )
    if not profile_id.isupper():
        raise ValueError(
            f"evidence_profile {profile_id!r} must be an upper-case "
            "QE EvidenceProfile id (e.g. CHEAP_SCREEN_CN_1D)"
        )
    return profile_id


@dataclass(frozen=True)
class StageEvaluationProfile:
    """A multi-fidelity stage bound to a named QE EvidenceProfile (plan §31).

    Attributes:
        stage: The canonical stage.
        evidence_profile: QE EvidenceProfile id string (policy
            ``QE_EVIDENCE_PROFILE``).  String reference only — FO never
            imports QE.  Fail-closed on empty / non-upper tokens so a typo'd
            id cannot silently become an unvalidated lower-case default.
        policy_id: Stable policy family (``FO_EVALUATION_STAGE``).
        policy_version: Semantic-version string.
    """

    stage: EvaluationStage
    evidence_profile: str = ""
    policy_id: str = "FO_EVALUATION_STAGE"
    policy_version: str = "1.0.0"

    def __post_init__(self) -> None:
        if not isinstance(self.stage, EvaluationStage):
            raise ValueError("stage must be an EvaluationStage member")
        object.__setattr__(
            self,
            "evidence_profile",
            _validate_profile_id(self.evidence_profile),
        )
        if not isinstance(self.policy_id, str) or not self.policy_id.strip():
            raise ValueError("policy_id must be a non-empty string")
        if not isinstance(self.policy_version, str) or not self.policy_version.strip():
            raise ValueError("policy_version must be a non-empty string")


