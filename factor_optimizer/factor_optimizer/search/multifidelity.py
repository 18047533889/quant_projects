@dataclass(frozen=True)
class Stage2DiagnosisBudget:
    """The diagnosis-directed candidate plan Stage 2 executes (plan §31).

    Wraps the FI-034 :class:`DiagnosisSearchBudget` generator output with the
    Stage-2 profile binding.  The candidate ceiling is the soft total budget's
    upper bound (6-12) — Stage 2 never floods hundreds of candidates.

    Attributes:
        stage_profile: The Stage2 StageEvaluationProfile.
        plan: The concrete diagnosis-directed candidate plan.
        budget_config: The config that produced the plan (defaults E5).
    """

    stage_profile: StageEvaluationProfile
    plan: DiagnosisSearchBudget
    budget_config: RepairBudgetConfig = field(default_factory=RepairBudgetConfig)

    def __post_init__(self) -> None:
        if not isinstance(self.stage_profile, StageEvaluationProfile):
            raise TypeError("stage_profile must be a StageEvaluationProfile")
        if self.stage_profile.stage is not EvaluationStage.STAGE2:
            raise ValueError(
                "Stage2DiagnosisBudget requires the STAGE2 profile"
            )
        if not isinstance(self.plan, DiagnosisSearchBudget):
            raise TypeError("plan must be a DiagnosisSearchBudget")

    @property
    def candidate_ceiling(self) -> int:
        return self.plan.total_candidates_ceiling

    def to_dict(self) -> Dict[str, Any]:
        return {
            "stage_profile": self.stage_profile,
            "plan": self.plan.to_dict(),
            "budget_config": self.budget_config,
        }


def build_stage2_budget(
    diagnoses: Sequence[DiagnosisKind | str],
    *,
    evidence: Optional[Mapping[str, object]] = None,
    budget_config: Optional[RepairBudgetConfig] = None,
    stage_registry: Optional[StageProfileRegistry] = None,
) -> Stage2DiagnosisBudget:
    """Build the Stage-2 diagnosis-directed budget for a factor (plan §31).

    The candidate budget is bounded 6-12 (soft); the Stage-2 profile binding
    is resolved from the versioned Stage registry (default
    ``SHAPE_DIAGNOSTIC_CN_1D`` for Stage 2).
    """
    stage_registry = stage_registry or StageProfileRegistry.default()
    profile = stage_registry.profile_for(EvaluationStage.STAGE2)
    plan = diagnosis_search_budget(
        diagnoses,
        evidence=evidence,
        config=budget_config,
    )
    return Stage2DiagnosisBudget(
        stage_profile=profile,
        plan=plan,
        budget_config=budget_config or RepairBudgetConfig(),
    )


