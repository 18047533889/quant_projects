@dataclass
class StageCostTelemetry:
    """Mutable per-stage cost accumulator (plan §31 cost telemetry).

    Attributes:
        stage: Stage this telemetry records.
        evidence_profile: QE EvidenceProfile id string (or ``"static"`` for
            Stage0 which never runs a QE profile).
        wall_time_s: Wall-clock seconds spent in this stage.
        cpu_time_s: CPU seconds spent.
        gpu_time_s: GPU kernel seconds (0 when no GPU kernel ran).
        h2d_d2h_bytes: Host↔device transfer bytes (0 when none).
        peak_vram_bytes: Peak device memory bytes (0 when unknown).
        bytes_read: Data bytes read by the stage.
        candidate_count: Number of candidates evaluated in the stage.
        metric_count: Number of metrics computed across the stage's
            evaluations.
        factor_value_cache_hits: Factor-value cache hits.
        policy_id / policy_version: Versioned stage-profile policy that this
            telemetry was recorded under.
    """

    stage: EvaluationStage
    evidence_profile: str = ""
    wall_time_s: float = 0.0
    cpu_time_s: float = 0.0
    gpu_time_s: float = 0.0
    h2d_d2h_bytes: int = 0
    peak_vram_bytes: int = 0
    bytes_read: int = 0
    candidate_count: int = 0
    metric_count: int = 0
    factor_value_cache_hits: int = 0
    policy_id: str = "FO_EVALUATION_STAGE"
    policy_version: str = "1.0.0"

    def __post_init__(self) -> None:
        if not isinstance(self.stage, EvaluationStage):
            raise ValueError("stage must be an EvaluationStage member")
        object.__setattr__(
            self,
            "evidence_profile",
            "static" if self.stage is EvaluationStage.STAGE0 else _validate_profile_id(
                self.evidence_profile
            ),
        )
        for name in (
            "wall_time_s",
            "cpu_time_s",
            "gpu_time_s",
        ):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise ValueError(f"{name} must be a number")
            if value < 0:
                raise ValueError(f"{name} must be non-negative")
            object.__setattr__(self, name, float(value))
        for name in (
            "h2d_d2h_bytes",
            "peak_vram_bytes",
            "bytes_read",
            "candidate_count",
            "metric_count",
            "factor_value_cache_hits",
        ):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int):
                raise ValueError(f"{name} must be an int")
            if value < 0:
                raise ValueError(f"{name} must be non-negative")

    def record_evaluation(
        self,
        *,
        candidate_count: int = 1,
        metric_count: int = 0,
        wall_time_s: float = 0.0,
        cpu_time_s: float = 0.0,
        gpu_time_s: float = 0.0,
        h2d_d2h_bytes: int = 0,
        peak_vram_bytes: int = 0,
        bytes_read: int = 0,
        factor_value_cache_hits: int = 0,
    ) -> None:
        """Accumulate one evaluation's costs into this stage telemetry."""
        for value in (candidate_count, metric_count, h2d_d2h_bytes,
                      peak_vram_bytes, bytes_read, factor_value_cache_hits):
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise ValueError("telemetry int counters must be non-negative ints")
        for value in (wall_time_s, cpu_time_s, gpu_time_s):
            if isinstance(value, bool) or not isinstance(value, (int, float)) or value < 0:
                raise ValueError("telemetry time counters must be non-negative numbers")
        self.candidate_count += candidate_count
        self.metric_count += metric_count
        self.wall_time_s += float(wall_time_s)
        self.cpu_time_s += float(cpu_time_s)
        self.gpu_time_s += float(gpu_time_s)
        self.h2d_d2h_bytes += h2d_d2h_bytes
        self.peak_vram_bytes = max(self.peak_vram_bytes, peak_vram_bytes)
        self.bytes_read += bytes_read
        self.factor_value_cache_hits += factor_value_cache_hits

    def to_dict(self) -> Dict[str, Any]:
        return {
            "stage": self.stage.name,
            "evidence_profile": self.evidence_profile,
            "wall_time_s": self.wall_time_s,
            "cpu_time_s": self.cpu_time_s,
            "gpu_time_s": self.gpu_time_s,
            "h2d_d2h_bytes": self.h2d_d2h_bytes,
            "peak_vram_bytes": self.peak_vram_bytes,
            "bytes_read": self.bytes_read,
            "candidate_count": self.candidate_count,
            "metric_count": self.metric_count,
            "factor_value_cache_hits": self.factor_value_cache_hits,
            "policy_id": self.policy_id,
            "policy_version": self.policy_version,
        }

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> "StageCostTelemetry":
        values = dict(data)
        values["stage"] = EvaluationStage[values["stage"]]
        return cls(**values)


@dataclass
class MultiStageCostTelemetry:
    """Accumulates one :class:`StageCostTelemetry` per stage (plan §31).

    Provides the scheduler a single record point: ``record_stage`` looks up
    (or creates) the stage's accumulator and merges the evaluation costs.
    This is a plain record — it performs no real GPU timing.
    """

    stage_profiles: StageProfileRegistry = field(
        default_factory=StageProfileRegistry.default
    )
    _per_stage: Dict[EvaluationStage, StageCostTelemetry] = field(
        default_factory=dict, init=False, repr=False
    )

    def telemetry_for(self, stage: EvaluationStage) -> StageCostTelemetry:
        if stage not in self._per_stage:
            profile = self.stage_profiles.profile_for(stage)
            self._per_stage[stage] = StageCostTelemetry(
                stage=stage,
                evidence_profile=profile.evidence_profile,
                policy_id=profile.policy_id,
                policy_version=profile.policy_version,
            )
        return self._per_stage[stage]

    def record_stage(
        self,
        stage: EvaluationStage,
        *,
        candidate_count: int = 1,
        metric_count: int = 0,
        wall_time_s: float = 0.0,
        cpu_time_s: float = 0.0,
        gpu_time_s: float = 0.0,
        h2d_d2h_bytes: int = 0,
        peak_vram_bytes: int = 0,
        bytes_read: int = 0,
        factor_value_cache_hits: int = 0,
    ) -> None:
        """Record one evaluation's costs into *stage*'s accumulator."""
        self.telemetry_for(stage).record_evaluation(
            candidate_count=candidate_count,
            metric_count=metric_count,
            wall_time_s=wall_time_s,
            cpu_time_s=cpu_time_s,
            gpu_time_s=gpu_time_s,
            h2d_d2h_bytes=h2d_d2h_bytes,
            peak_vram_bytes=peak_vram_bytes,
            bytes_read=bytes_read,
            factor_value_cache_hits=factor_value_cache_hits,
        )

    def report(self) -> Dict[str, Any]:
        """Structured telemetry report (stage -> StageCostTelemetry.to_dict())."""
        return {
            stage.name: self._per_stage[stage].to_dict()
            for stage in sorted(self._per_stage, key=lambda s: s.value)
        }

    def to_dict(self) -> Dict[str, Any]:
        return {
            "stage_profiles": self.stage_profiles.to_dict(),
            "per_stage": self.report(),
        }


@dataclass(frozen=True)
class FidelitySpec:
    """
    Specification for evaluation at a specific fidelity tier.

    Attributes:
        tier: Fidelity tier level
        sample_fraction: Fraction of full dataset to use
        num_metrics: Number of metrics to compute
        cross_validate: Whether to perform cross-validation
        compute_robustness: Whether to compute robustness checks
        cost_multiplier: Relative cost compared to L0
        typical_duration_ms: Typical evaluation duration
    """
    tier: FidelityTier
    sample_fraction: float
    num_metrics: int
    cross_validate: bool = False
    compute_robustness: bool = False
    cost_multiplier: float = 1.0
    typical_duration_ms: int = 100

    def __post_init__(self):
        if not 0 < self.sample_fraction <= 1.0:
            raise ValueError("sample_fraction must be in (0, 1]")
        if self.num_metrics < 1:
            raise ValueError("num_metrics must be >= 1")
        if self.cost_multiplier <= 0:
            raise ValueError("cost_multiplier must be > 0")


