class StageProfileRegistry:
    """Versioned registry mapping each EvaluationStage to its evidence profile.

    Immutable after construction; the default carries the canonical
    Stage0-5 bindings (plan §31).  ``profile_for`` resolves a stage; an
    unknown stage fails closed with a typed ``ValueError``.
    """

    def __init__(
        self,
        profiles: Sequence[StageEvaluationProfile],
        policy_id: str = "FO_EVALUATION_STAGE",
        policy_version: str = "1.0.0",
    ) -> None:
        if not isinstance(profiles, (list, tuple)) or not profiles:
            raise ValueError("stage profile registry requires a non-empty profile list")
        if not all(isinstance(p, StageEvaluationProfile) for p in profiles):
            raise TypeError(
                "stage profiles must be StageEvaluationProfile instances"
            )
        stages = [p.stage for p in profiles]
        if len(stages) != len(set(stages)):
            raise ValueError("stage profile registry has duplicate stages")
        self._profiles: Dict[EvaluationStage, StageEvaluationProfile] = {
            p.stage: p for p in profiles
        }
        self._policy_id = policy_id
        self._policy_version = policy_version
        for p in profiles:
            if p.policy_id != policy_id:
                raise ValueError(
                    f"stage profile {p.stage.name} policy_id {p.policy_id!r} "
                    f"does not match registry {policy_id!r}"
                )

    @classmethod
    def default(cls) -> "StageProfileRegistry":
        """The canonical Stage0-5 registry (plan §31)."""
        return cls(DEFAULT_STAGE_PROFILES)

    @property
    def policy_id(self) -> str:
        return self._policy_id

    @property
    def policy_version(self) -> str:
        return self._policy_version

    def profile_for(self, stage: EvaluationStage | int) -> StageEvaluationProfile:
        if isinstance(stage, int):
            try:
                stage = EvaluationStage(stage)
            except ValueError:
                raise ValueError(f"unknown evaluation stage {stage!r}") from None
        try:
            return self._profiles[stage]
        except KeyError:
            raise ValueError(
                f"evaluation stage {stage.name} has no registered profile"
            ) from None

    @property
    def stages(self) -> Tuple[EvaluationStage, ...]:
        return tuple(sorted(self._profiles, key=lambda s: s.value))

    def evidence_profiles(self) -> Dict[str, str]:
        """Stage name → evidence-profile id (string reference) mapping."""
        return {
            p.stage.name: p.evidence_profile for p in self._profiles.values()
        }

    def __len__(self) -> int:
        return len(self._profiles)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "policy_id": self._policy_id,
            "policy_version": self._policy_version,
            "profiles": [
                {
                    "stage": p.stage.name,
                    "evidence_profile": p.evidence_profile,
                    "policy_id": p.policy_id,
                    "policy_version": p.policy_version,
                }
                for p in self._profiles.values()
            ],
        }


