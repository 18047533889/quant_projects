class TestComplexDataFlows:
    """Test complex multi-backend data flows."""

    def test_join_across_backends(self, sample_panel_data):
        """Test join operation across different backends."""
        df1 = sample_panel_data[["date", "instrument", "close"]].copy()
        df2 = sample_panel_data[["date", "instrument", "volume"]].copy()

        # Join in Pandas (simulates cross-backend join)
        result = pd.merge(
            df1,
            df2,
            on=["date", "instrument"],
            how="inner"
        )

        assert len(result) == len(sample_panel_data)
        assert "close" in result.columns
        assert "volume" in result.columns

    def test_aggregation_then_rolling(self, sample_panel_data):
        """Test aggregation (SQL) then rolling (Polars) workflow."""
        df = sample_panel_data.copy()

        # Step 1: Aggregation (would use DuckDB)
        daily_agg = df.groupby("date").agg({
            "close": "mean",
            "volume": "sum"
        }).reset_index()

        # Step 2: Rolling window (would use Polars)
        daily_agg = daily_agg.sort_values("date")
        daily_agg["close_ma"] = daily_agg["close"].rolling(window=5).mean()

        assert "close_ma" in daily_agg.columns
        assert len(daily_agg) == df["date"].nunique()

    def test_multi_way_merge(self, sample_panel_data):
        """Test multi-way merge from different backends."""
        df = sample_panel_data.copy()

        # Three separate computations (could be different backends)
        df1 = df[["date", "instrument", "close"]].copy()
        df1["feature1"] = df1["close"] * 2

        df2 = df[["date", "instrument", "volume"]].copy()
        df2["feature2"] = df2["volume"] / 1000

        df3 = df[["date", "instrument", "returns"]].copy()
        df3["feature3"] = df3["returns"].abs()

        # Merge all three
        result = df1.merge(df2, on=["date", "instrument"])
        result = result.merge(df3, on=["date", "instrument"])

        assert all(col in result.columns for col in ["feature1", "feature2", "feature3"])
        assert len(result) == len(sample_panel_data)