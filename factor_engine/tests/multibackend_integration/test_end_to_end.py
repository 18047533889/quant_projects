class TestSimpleFactorComputation:
    """Test simple end-to-end factor computation."""

    def test_single_backend_simple_factor(self, sample_panel_data):
        """Test simple factor on single backend."""
        df = sample_panel_data.copy()

        # Compute simple moving average factor
        df = df.sort_values(["instrument", "date"])
        df["sma_5"] = df.groupby("instrument")["close"].transform(
            lambda x: x.rolling(window=5, min_periods=1).mean()
        )

        assert "sma_5" in df.columns
        assert not df["sma_5"].isna().all()
        assert len(df) == len(sample_panel_data)

    def test_multi_backend_composite_factor(self, sample_panel_data):
        """Test composite factor requiring multiple backends."""
        df = sample_panel_data.copy()

        # Step 1: Time-series features (Polars/Pandas)
        df = df.sort_values(["instrument", "date"])
        df["returns_ma"] = df.groupby("instrument")["returns"].transform(
            lambda x: x.rolling(window=10, min_periods=1).mean()
        )

        # Step 2: Cross-sectional rank (would use DuckDB)
        df["rank_volume"] = df.groupby("date")["volume"].rank(pct=True)

        # Step 3: Combine
        df["composite"] = df["returns_ma"] * df["rank_volume"]

        assert "composite" in df.columns
        assert not df["composite"].isna().all()


class TestLargeScaleBatch:
    """Test large-scale batch processing."""

    def test_batch_100_factors(self, sample_panel_data):
        """Test computing 100 factors in batch."""
        df = sample_panel_data.copy()
        df = df.sort_values(["instrument", "date"])

        # Simulate computing 100 simple factors
        for i in range(10):  # 10 factors for test speed
            window = 5 + i
            df[f"sma_{window}"] = df.groupby("instrument")["close"].transform(
                lambda x: x.rolling(window=window, min_periods=1).mean()
            )

        # Check all factors computed
        for i in range(10):
            assert f"sma_{5+i}" in df.columns

    def test_batch_1000_factors_plan_only(self):
        """Test planning for 1000 factors (plan only, no execution)."""
        # Create a plan for 1000 factors
        # In practice, this would be generated by the planner

        num_factors = 1000
        factors_per_region = 50

        regions = []
        for i in range(num_factors // factors_per_region):
            node_ids = tuple(f"n{i*factors_per_region + j}" for j in range(factors_per_region))
            regions.append(
                BackendRegion(
                    region_id=f"r{i}",
                    backend=PhysicalBackend.POLARS_PANEL,
                    representation=Representation.POLARS_LONG,
                    node_ids=node_ids,
                    execution_axis=ExecutionAxis.TIME_PER_INSTRUMENT,
                    required_properties=PhysicalProperties(),
                    state_contract=StateContract(),
                    estimated_rows=100_000,
                    estimated_compute_ms=50.0,
                    estimated_memory_bytes=8_000_000,
                )
            )

        plan = PhysicalRegionPlan(
            plan_id="large_batch_plan",
            regions=tuple(regions),
            edges=(),
            topological_order=tuple(f"r{i}" for i in range(len(regions))),
            root_region_ids=tuple(f"r{i}" for i in range(len(regions))),
            total_compute_ms=5000.0,
            total_transfer_ms=0.0,
            total_ttdc_ms=5000.0,
            peak_memory_bytes=160_000_000,
            logical_node_count=num_factors,
            backend_switch_count=0,
            native_fraction=0.95,
        )

        assert plan.logical_node_count == num_factors
        assert len(plan.regions) == num_factors // factors_per_region

    def test_large_batch_memory_tracking(self, large_panel_data):
        """Test memory tracking for large batch."""
        df = large_panel_data.copy()

        # Estimate memory usage
        initial_memory = df.memory_usage(deep=True).sum()

        # Compute several factors
        df = df.sort_values(["instrument", "date"])
        for i in range(5):
            df[f"feature_{i}"] = df.groupby("instrument")["close"].transform(
                lambda x: x.rolling(window=10+i, min_periods=1).mean()
            )

        final_memory = df.memory_usage(deep=True).sum()

        # Memory should increase with new columns
        assert final_memory > initial_memory


