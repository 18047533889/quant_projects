# ---------------------------------------------------------------------------
# Metadata validation
# ---------------------------------------------------------------------------
def test_multifractal_metadata() -> None:
    """Verify all operators have correct metadata."""
    operators = [
        "ts_generalized_hurst_exponent",
        "ts_generalized_hurst_spread_q1_q4",
        "ts_multifractal_spectrum_width",
        "ts_multifractal_curvature"
    ]

    for op_name in operators:
        op = _op(op_name)
        meta = getattr(op, "metadata", None)
        assert meta is not None, f"{op_name} missing metadata"
        assert hasattr(meta, "tags"), f"{op_name} missing tags"
