# Metadata validation
# ---------------------------------------------------------------------------
def test_downside_risk_metadata() -> None:
    """Verify all operators have correct metadata."""
    operators = [
        "ts_downside_deviation",
        "ts_upside_deviation",
        "ts_current_drawdown_duration",
        "ts_time_under_water",
        "ts_best_lag_corr_raw",
        "ts_best_lag_corr_excess",
        "ts_price_delay"
    ]

    for op_name in operators:
        op = _op(op_name)
        meta = getattr(op, "metadata", None)
        assert meta is not None, f"{op_name} missing metadata"
        assert hasattr(meta, "tags"), f"{op_name} missing tags"
