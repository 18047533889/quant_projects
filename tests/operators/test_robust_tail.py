# Metadata validation
# ---------------------------------------------------------------------------
def test_robust_tail_metadata() -> None:
    """Verify all operators have correct metadata."""
    operators = [
        "ts_lower_partial_moment",
        "ts_upper_partial_moment",
        "ts_expected_shortfall",
        "ts_quantile_skew",
        "ts_quantile_kurtosis",
        "ts_tail_ratio",
        "ts_extreme_cluster_ratio"
    ]

    for op_name in operators:
        op = _op(op_name)
        meta = getattr(op, "metadata", None)
        assert meta is not None, f"{op_name} missing metadata"
        assert hasattr(meta, "tags"), f"{op_name} missing tags"
        assert meta.name == op_name, f"{op_name} name mismatch"
